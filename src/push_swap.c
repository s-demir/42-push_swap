#include "push_swap.h"

static void	sort(t_stack **a, t_stack **b)
{
	int	size;

	size = stack_size(*a);
	if (size == 2)
		sort_two(a);
	else if (size == 3)
		sort_three(a);
	else if (size <= 5)
		sort_five(a, b);
	else
		sort_large(a, b);
}

int	main(int argc, char **argv)
{
	t_stack	*a;
	t_stack	*b;

	if (argc < 2)
		return (0);
	b = NULL;
	a = parse_args(argc, argv);
	if (!a)
	{
		ft_putstr_fd("Error\n", 2);
		exit(1);
	}
	if (!stack_is_sorted(a))
		sort(&a, &b);
	free_stack(&a);
	free_stack(&b);
	return (0);
}
